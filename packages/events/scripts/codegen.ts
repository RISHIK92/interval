// Generates the event types from events.json (DB-5, Q-P1-20): zod schemas for the web
// app and pydantic models for the worker, so the list exists once (ARCH-2).
// Usage: node scripts/codegen.ts <events.json> <ts out> <py out>
import { readFileSync, writeFileSync } from "node:fs";

// "id": a row id (a positive bigint) as a string; "id?": the same, or null.
type PropType = "count" | "string" | "boolean" | "id" | "id?" | string[];
type EventSpec = {
  version: number;
  description: string;
  props: Record<string, PropType>;
};
type Spec = {
  envelope: { beta_group: string[]; source: string[] };
  events: Record<string, EventSpec>;
};

const [specPath, tsOut, pyOut] = process.argv.slice(2);
if (specPath === undefined || tsOut === undefined || pyOut === undefined) {
  throw new Error("usage: codegen.ts <events.json> <ts out> <py out>");
}
const spec = JSON.parse(readFileSync(specPath, "utf8")) as Spec;
const names = Object.keys(spec.events).sort();

for (const name of names) {
  if (!/^[a-z]+(_[a-z]+)+$/.test(name))
    throw new Error(`${name}: not object_action`);
  const event = spec.events[name];
  if (
    event === undefined ||
    !Number.isInteger(event.version) ||
    event.version < 1
  ) {
    throw new Error(`${name}: version must be a positive integer`);
  }
  for (const [prop, type] of Object.entries(event.props)) {
    const ok = Array.isArray(type)
      ? type.length > 0 && type.every((v) => typeof v === "string")
      : ["count", "string", "boolean", "id", "id?"].includes(type);
    if (!ok)
      throw new Error(`${name}.${prop}: unknown type ${JSON.stringify(type)}`);
  }
}

const quote = (s: string): string => JSON.stringify(s);
const pascal = (s: string): string =>
  s.replace(/(^|_)([a-z])/g, (_m, _sep: string, c: string) => c.toUpperCase());
const eventOf = (name: string): EventSpec => {
  const event = spec.events[name];
  if (event === undefined) throw new Error(name);
  return event;
};

// The same row-id pattern the web app checks forms with (BIGINT_ID in server/ports.ts).
const ID_PATTERN = "^[1-9][0-9]{0,18}$";

function zodType(type: PropType): string {
  if (Array.isArray(type)) return `z.enum([${type.map(quote).join(", ")}])`;
  if (type === "count") return "z.number().int().nonnegative()";
  if (type === "id") return `z.string().regex(/${ID_PATTERN}/)`;
  if (type === "id?") return `z.string().regex(/${ID_PATTERN}/).nullable()`;
  return type === "string" ? "z.string()" : "z.boolean()";
}

function pyType(type: PropType): string {
  if (Array.isArray(type)) return `Literal[${type.map(quote).join(", ")}]`;
  if (type === "count") return "int = Field(ge=0, strict=True)";
  if (type === "id") return `str = Field(pattern=r"${ID_PATTERN}")`;
  if (type === "id?") return `str | None = Field(pattern=r"${ID_PATTERN}")`;
  return type === "string" ? "str" : "StrictBool";
}

const header =
  "Generated by packages/events/scripts/codegen.ts from events.json. Do not edit.";

const ts = `// ${header}
import { z } from "zod";

export const EVENT_NAMES = [${names.map(quote).join(", ")}] as const;
export type EventName = (typeof EVENT_NAMES)[number];

export const EVENT_VERSIONS = {
${names.map((n) => `  ${n}: ${String(eventOf(n).version)},`).join("\n")}
} as const satisfies Record<EventName, number>;

export const propsSchemas = {
${names
  .map((n) => {
    const fields = Object.entries(eventOf(n).props)
      .map(([prop, type]) => `${prop}: ${zodType(type)}`)
      .join(", ");
    return `  ${n}: z.strictObject({${fields === "" ? "" : ` ${fields} `}}),`;
  })
  .join("\n")}
} as const;

export type EventProps = { [N in EventName]: z.infer<(typeof propsSchemas)[N]> };

const base = {
  event_id: z.uuid(),
  occurred_at: z.iso.datetime(),
  user_id: z.string().min(1),
  is_guest: z.boolean(),
  beta_group: z.enum([${spec.envelope.beta_group.map(quote).join(", ")}]),
  session_id: z.string().min(1).nullable(),
  source: z.enum([${spec.envelope.source.map(quote).join(", ")}]),
};

// Q-P1-20: every event carries the same envelope; name and version pick its props.
export const envelopeSchema = z.discriminatedUnion("name", [
${names
  .map(
    (n) =>
      `  z.strictObject({ ...base, name: z.literal(${quote(n)}), version: z.literal(${String(eventOf(n).version)}), props: propsSchemas.${n} }),`,
  )
  .join("\n")}
]);
export type Envelope = z.infer<typeof envelopeSchema>;
`;

const py = `"""${header}"""

from datetime import UTC
from typing import Annotated, Literal
from uuid import UUID

from pydantic import (
    AwareDatetime,
    BaseModel,
    ConfigDict,
    Field,
    StrictBool,
    field_serializer,
)

type EventName = Literal[${names.map(quote).join(", ")}]
type BetaGroup = Literal[${spec.envelope.beta_group.map(quote).join(", ")}]
type Source = Literal[${spec.envelope.source.map(quote).join(", ")}]

EVENT_VERSIONS: dict[EventName, int] = {
${names.map((n) => `    ${quote(n)}: ${String(eventOf(n).version)},`).join("\n")}
}


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

${names
  .map((n) => {
    const fields = Object.entries(eventOf(n).props).map(
      ([prop, type]) => `    ${prop}: ${pyType(type)}`,
    );
    return `
class ${pascal(n)}Props(_Model):
${fields.length === 0 ? "    pass" : fields.join("\n")}
`;
  })
  .join("")}

class _EnvelopeBase(_Model):
    event_id: UUID
    occurred_at: AwareDatetime
    user_id: str = Field(min_length=1)
    is_guest: StrictBool
    beta_group: BetaGroup
    session_id: str | None = Field(min_length=1)
    source: Source

    # The web app's format (toISOString): UTC with milliseconds, so Athena reads one.
    @field_serializer("occurred_at")
    def _utc_milliseconds(self, value: AwareDatetime) -> str:
        utc = value.astimezone(UTC).isoformat(timespec="milliseconds")
        return utc.replace("+00:00", "Z")
${names
  .map(
    (n) => `

class ${pascal(n)}Event(_EnvelopeBase):
    name: Literal[${quote(n)}]
    version: Literal[${String(eventOf(n).version)}]
    props: ${pascal(n)}Props
`,
  )
  .join("")}

# Q-P1-20: every event carries the same envelope; name and version pick its props.
type Envelope = Annotated[
    ${names.map((n) => `${pascal(n)}Event`).join(" | ")},
    Field(discriminator="name"),
]
`;

writeFileSync(tsOut, ts);
writeFileSync(pyOut, py);
