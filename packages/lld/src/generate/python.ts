import type { Interface } from "../interface";
import type { TypeAst } from "../types";
import { type Generated, methodsOf } from "./common";

const py = (t: TypeAst): string => {
  switch (t.kind) {
    case "int":
      return "int";
    case "float":
      return "float";
    case "bool":
      return "bool";
    case "string":
      return "str";
    case "list":
      return `list[${py(t.of)}]`;
    case "map":
      return `dict[str, ${py(t.of)}]`;
    case "optional":
      return `${py(t.of)} | None`;
  }
};

export function python(iface: Interface): Generated {
  const { ctor, methods } = methodsOf(iface);
  const sig = (ps: typeof ctor) =>
    ["self", ...ps.map((p) => `${p.name}: ${py(p.type)}`)].join(", ");
  const starter = [
    "from __future__ import annotations",
    "",
    "",
    `class ${iface.class}:`,
    `    def __init__(${sig(ctor)}) -> None:`,
    "        pass",
    ...methods.flatMap((m) => [
      "",
      `    def ${m.name}(${sig(m.params)}) -> ${m.returns === "void" ? "None" : py(m.returns)}:`,
      "        raise NotImplementedError",
    ]),
    "",
  ].join("\n");
  const args = (n: number) =>
    Array.from({ length: n }, (_, i) => `a[${String(i)}]`).join(", ");
  // One dispatch, for the main calls and the threads alike (no reflection).
  const dispatch = [
    "def _call(obj, m, a):",
    ...methods.flatMap((x, k) => [
      `    ${k === 0 ? "if" : "elif"} m == "${x.name}":`,
      x.returns === "void"
        ? `        obj.${x.name}(${args(x.params.length)})\n        return None`
        : `        return obj.${x.name}(${args(x.params.length)})`,
    ]),
    '    raise ValueError("unknown method " + m)',
  ];
  const harness = [
    "# Generated by @interval/lld (P5-W29-S02, S02b); do not edit.",
    "import json",
    "import os",
    "import sys",
    "import threading",
    "",
    "sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))",
    "_out = sys.stdout",
    "# The submission's own prints go to stderr, never into the results.",
    "sys.stdout = sys.stderr",
    `from solution import ${iface.class}  # noqa: E402`,
    "",
    "",
    "def _clean(e):",
    "    try:",
    '        s = type(e).__name__ + ": " + str(e)',
    "    except BaseException:",
    "        s = type(e).__name__",
    '    return "".join(c if " " <= c <= "~" else "?" for c in s)[:200]',
    "",
    "",
    ...dispatch,
    "",
    "",
    "def _threads(obj, threads):",
    "    # Started together behind a barrier, so they really collide; a thread's own",
    "    # results and errors aren't reported (P5-W30-S02b).",
    "    gate = threading.Barrier(len(threads))",
    "",
    "    def run(calls):",
    "        try:",
    "            gate.wait()",
    "        except threading.BrokenBarrierError:",
    "            return",
    "        for c in calls:",
    "            try:",
    '                _call(obj, c["method"], c["args"])',
    "            except BaseException:  # noqa: BLE001, S110",
    "                pass",
    "",
    "    workers = [threading.Thread(target=run, args=(t,)) for t in threads]",
    "    try:",
    "        for w in workers:",
    "            w.start()",
    "    except BaseException:",
    "        # The started threads would wait at the barrier forever: release them, then",
    "        # end the run as a crash, never a timeout.",
    "        gate.abort()",
    "        raise",
    "    for w in workers:",
    "        w.join()",
    "",
    "",
    "def _main():",
    "    scenario = json.load(sys.stdin)",
    '    calls, concurrent = scenario["calls"], scenario.get("concurrent")',
    "    lines = []",
    "    obj = None",
    "    for i, c in enumerate(calls):",
    '        if concurrent is not None and i == concurrent["after"]:',
    '            _threads(obj, concurrent["threads"])',
    '        m, a = c["method"], c["args"]',
    "        try:",
    "            v = None",
    `            if m == "new":`,
    `                obj = ${iface.class}(${args(ctor.length)})`,
    "            else:",
    "                v = _call(obj, m, a)",
    '            lines.append(json.dumps({"call": i, "value": v}, allow_nan=False))',
    "        except BaseException as e:  # noqa: BLE001 (sys.exit() too: an error line, never a lost run)",
    '            lines.append(json.dumps({"call": i, "error": _clean(e)}))',
    '    _out.write("".join(line + "\\n" for line in lines))',
    "    _out.flush()",
    "    # A submission's leftover threads must not keep the run alive past its results.",
    "    os._exit(0)",
    "",
    "",
    "_main()",
    "",
  ].join("\n");
  return {
    solutionFile: "solution.py",
    starter,
    harnessFile: "main.py",
    harness,
  };
}
