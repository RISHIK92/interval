import type { Interface } from "../interface";
import type { TypeAst } from "../types";
import { type Generated, methodsOf } from "./common";

const gt = (t: TypeAst): string => {
  switch (t.kind) {
    case "int":
      return "int64";
    case "float":
      return "float64";
    case "bool":
      return "bool";
    case "string":
      return "string";
    case "list":
      return `[]${gt(t.of)}`;
    case "map":
      return `map[string]${gt(t.of)}`;
    case "optional":
      return `*${gt(t.of)}`;
  }
};

// Go's nil slice or map marshals as null where every other language gives [] or {}: a
// generated normaliser per return type makes them empty, recursing into elements, and
// leaves an optional's nil as null. No reflection: one small function per type.
function normalisers(types: TypeAst[]): {
  fn: Map<string, string>;
  code: string[];
} {
  const fn = new Map<string, string>();
  const code: string[] = [];
  const needs = (t: TypeAst): boolean =>
    t.kind === "list" ||
    t.kind === "map" ||
    (t.kind === "optional" && needs(t.of));
  const name = (t: TypeAst): string => {
    const key = gt(t);
    const known = fn.get(key);
    if (known !== undefined) return known;
    const n = `intervalNorm${String(fn.size)}`;
    fn.set(key, n);
    const inner = "of" in t && needs(t.of) ? name(t.of) : null;
    if (t.kind === "list")
      code.push(
        `func ${n}(v ${key}) ${key} {\n\tif v == nil {\n\t\tv = ${key}{}\n\t}\n${inner === null ? "" : `\tfor i := range v {\n\t\tv[i] = ${inner}(v[i])\n\t}\n`}\treturn v\n}`,
      );
    else if (t.kind === "map")
      code.push(
        `func ${n}(v ${key}) ${key} {\n\tif v == nil {\n\t\tv = ${key}{}\n\t}\n${inner === null ? "" : `\tfor k := range v {\n\t\tv[k] = ${inner}(v[k])\n\t}\n`}\treturn v\n}`,
      );
    else if (t.kind === "optional" && inner !== null)
      code.push(
        `func ${n}(v ${key}) ${key} {\n\tif v == nil {\n\t\treturn nil\n\t}\n\tx := ${inner}(*v)\n\treturn &x\n}`,
      );
    return n;
  };
  for (const t of types) if (needs(t)) name(t);
  return { fn, code };
}

export function go(iface: Interface): Generated {
  const { ctor, methods } = methodsOf(iface);
  const sig = (ps: typeof ctor) =>
    ps.map((p) => `${p.name} ${gt(p.type)}`).join(", ");
  const norm = normalisers(
    methods.flatMap((m) => (m.returns === "void" ? [] : [m.returns])),
  );
  const starter = [
    "package main",
    "",
    `type ${iface.class} struct{}`,
    "",
    `func New${iface.class}(${sig(ctor)}) *${iface.class} {`,
    `\treturn &${iface.class}{}`,
    "}",
    ...methods.flatMap((m) => [
      "",
      `func (s *${iface.class}) ${m.name}(${sig(m.params)})${m.returns === "void" ? "" : ` ${gt(m.returns)}`} {`,
      '\tpanic("not implemented")',
      "}",
    ]),
    "",
  ].join("\n");
  // Each arg is decoded straight into a typed variable. The harness's own names are
  // prefixed and its imports aliased: it shares package main with the player's file.
  const decode = (ps: typeof ctor) =>
    ps.map(
      (p, i) =>
        `\t\tvar a${String(i)} ${gt(p.type)}\n\t\tintervalArg(c.Args, ${String(i)}, &a${String(i)})`,
    );
  const names = (ps: typeof ctor) =>
    ps.map((_, i) => `a${String(i)}`).join(", ");
  const call = (x: (typeof methods)[number]) => {
    const expr = `(*obj).${x.name}(${names(x.params)})`;
    if (x.returns === "void") return `\t\t${expr}`;
    const n = norm.fn.get(gt(x.returns));
    return `\t\tv = ${n === undefined ? expr : `${n}(${expr})`}`;
  };
  const arms = [
    '\tcase "new":',
    ...decode(ctor),
    `\t\t*obj = New${iface.class}(${names(ctor)})`,
    ...methods.flatMap((x) => [
      `\tcase "${x.name}":`,
      `\t\tif *obj == nil {\n\t\t\tpanic("no instance: the constructor failed")\n\t\t}`,
      ...decode(x.params),
      call(x),
    ]),
    "\tdefault:",
    '\t\tpanic("unknown method " + c.Method)',
  ];
  const harness = [
    "// Generated by @interval/lld (P5-W29-S02); do not edit.",
    "package main",
    "",
    "import (",
    '\tintervalBufio "bufio"',
    '\tintervalJSON "encoding/json"',
    '\tintervalFmt "fmt"',
    '\tintervalIO "io"',
    '\tintervalOS "os"',
    '\tintervalStrings "strings"',
    ")",
    "",
    "type intervalCall struct {",
    '\tMethod string                    `json:"method"`',
    '\tArgs   []intervalJSON.RawMessage `json:"args"`',
    "}",
    "",
    "func intervalArg(args []intervalJSON.RawMessage, i int, into any) {",
    "\tif i >= len(args) {",
    '\t\tpanic(intervalFmt.Sprintf("arg %d missing", i+1))',
    "\t}",
    "\tif err := intervalJSON.Unmarshal(args[i], into); err != nil {",
    "\t\tpanic(err)",
    "\t}",
    "}",
    "",
    "func intervalClean(s string) string {",
    "\tvar b intervalStrings.Builder",
    "\tfor _, r := range s {",
    "\t\tif r >= ' ' && r <= '~' {",
    "\t\t\tb.WriteRune(r)",
    "\t\t} else {",
    "\t\t\tb.WriteByte('?')",
    "\t\t}",
    "\t}",
    "\tout := b.String()",
    "\tif len(out) > 200 {",
    "\t\tout = out[:200]",
    "\t}",
    "\treturn out",
    "}",
    "",
    ...norm.code.map((c) => `${c}\n`),
    `func intervalRun(i int, c intervalCall, obj **${iface.class}) (line string) {`,
    "\tdefer func() {",
    "\t\tif r := recover(); r != nil {",
    '\t\t\tb, _ := intervalJSON.Marshal(map[string]any{"call": i, "error": intervalClean(intervalFmt.Sprint("panic: ", r))})',
    "\t\t\tline = string(b)",
    "\t\t}",
    "\t}()",
    "\tvar v any",
    "\tswitch c.Method {",
    ...arms,
    "\t}",
    "\tb, err := intervalJSON.Marshal(struct {",
    '\t\tCall  int `json:"call"`',
    '\t\tValue any `json:"value"`',
    "\t}{i, v})",
    "\tif err != nil {",
    "\t\tpanic(err)",
    "\t}",
    "\treturn string(b)",
    "}",
    "",
    "func main() {",
    "\treal := intervalOS.Stdout",
    "\t// The submission's own prints go to stderr, never into the results.",
    "\tintervalOS.Stdout = intervalOS.Stderr",
    "\tdata, err := intervalIO.ReadAll(intervalOS.Stdin)",
    "\tif err != nil {",
    "\t\tintervalOS.Exit(1)",
    "\t}",
    "\tvar scenario struct {",
    '\t\tCalls []intervalCall `json:"calls"`',
    "\t}",
    "\tif err := intervalJSON.Unmarshal(data, &scenario); err != nil {",
    "\t\tintervalOS.Exit(1)",
    "\t}",
    `\tvar obj *${iface.class}`,
    "\tout := intervalBufio.NewWriter(real)",
    "\tfor i, c := range scenario.Calls {",
    '\t\tout.WriteString(intervalRun(i, c, &obj) + "\\n")',
    "\t}",
    "\tout.Flush()",
    "\tintervalOS.Exit(0)",
    "}",
    "",
  ].join("\n");
  return {
    solutionFile: "solution.go",
    starter,
    harnessFile: "main.go",
    harness,
  };
}
