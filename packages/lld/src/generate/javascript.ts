import type { Interface } from "../interface";
import type { TypeAst } from "../types";
import { type Generated, methodsOf } from "./common";

const ts = (t: TypeAst): string => {
  switch (t.kind) {
    case "int":
    case "float":
      return "number";
    case "bool":
      return "boolean";
    case "string":
      return "string";
    case "list":
      return `${t.of.kind === "optional" ? `(${ts(t.of)})` : ts(t.of)}[]`;
    case "map":
      return `Record<string, ${ts(t.of)}>`;
    case "optional":
      return `${ts(t.of)} | null`;
  }
};

// JavaScript and TypeScript share one harness: TypeScript's only adds an ES import of
// a .ts file (Node's type stripping), JavaScript's a CommonJS require.
function generate(iface: Interface, typed: boolean): Generated {
  const { ctor, methods } = methodsOf(iface);
  const sig = (ps: typeof ctor) =>
    ps.map((p) => (typed ? `${p.name}: ${ts(p.type)}` : p.name)).join(", ");
  const ret = (r: TypeAst | "void") =>
    typed ? `: ${r === "void" ? "void" : ts(r)}` : "";
  const starter = [
    `${typed ? "export " : ""}class ${iface.class} {`,
    `  constructor(${sig(ctor)}) {}`,
    ...methods.flatMap((m) => [
      "",
      `  ${m.name}(${sig(m.params)})${ret(m.returns)} {`,
      '    throw new Error("not implemented");',
      "  }",
    ]),
    "}",
    ...(typed ? [] : ["", `module.exports = { ${iface.class} };`]),
    "",
  ].join("\n");
  const args = (n: number) =>
    Array.from({ length: n }, (_, i) => `a[${String(i)}]`).join(", ");
  const arms = [
    '      case "new":',
    `        obj = new ${iface.class}(${args(ctor.length)});`,
    "        break;",
    ...methods.flatMap((x) => [
      `      case "${x.name}":`,
      x.returns === "void"
        ? `        obj.${x.name}(${args(x.params.length)});`
        : `        v = obj.${x.name}(${args(x.params.length)});`,
      "        break;",
    ]),
    "      default:",
    '        throw new Error("unknown method " + c.method);',
  ];
  const any = typed ? ": any" : "";
  const harness = [
    "// Generated by @interval/lld (P5-W29-S02); do not edit.",
    typed ? 'import { readFileSync } from "node:fs";' : '"use strict";',
    ...(typed ? [] : ['const { readFileSync } = require("node:fs");']),
    "const write = process.stdout.write.bind(process.stdout);",
    "// The submission's own prints go to stderr, never into the results.",
    "console.log = console.error;",
    "console.info = console.error;",
    "console.debug = console.error;",
    `process.stdout.write = process.stderr.write.bind(process.stderr)${typed ? " as typeof process.stdout.write" : ""};`,
    typed
      ? `const { ${iface.class} } = await import("./solution.ts");`
      : `const { ${iface.class} } = require("./solution.js");`,
    `function clean(e${any})${typed ? ": string" : ""} {`,
    "  let s;",
    "  try {",
    '    s = (e && e.name ? e.name : "Error") + ": " + (e && e.message !== undefined ? e.message : String(e));',
    "  } catch {",
    '    s = "Error";',
    "  }",
    '  return s.replace(/[^\\x20-\\x7e]/g, "?").slice(0, 200);',
    "}",
    "// JSON has no NaN or Infinity: such a result is the call's error, not a silent null.",
    `function finite(_k${any}, v${any}) {`,
    '  if (typeof v === "number" && !Number.isFinite(v)) throw new RangeError("not a finite number");',
    "  return v;",
    "}",
    `const calls = JSON.parse(readFileSync(0, "utf8")).calls;`,
    `const out${typed ? ": string[]" : ""} = [];`,
    `let obj${any} = null;`,
    `calls.forEach((c${any}, i${typed ? ": number" : ""}) => {`,
    "  const a = c.args;",
    "  try {",
    `    let v${any} = null;`,
    "    switch (c.method) {",
    ...arms,
    "    }",
    "    if (v === undefined) v = null;",
    '    if (typeof v === "function" || typeof v === "symbol") throw new TypeError("not a JSON value");',
    "    out.push(JSON.stringify({ call: i, value: v }, finite));",
    "  } catch (e) {",
    "    out.push(JSON.stringify({ call: i, error: clean(e) }));",
    "  }",
    "});",
    'write(out.map((l) => l + "\\n").join(""), () => {',
    "  // A submission's leftover timers must not keep the run alive past its results.",
    "  process.exit(0);",
    "});",
    "",
  ].join("\n");
  return typed
    ? { solutionFile: "solution.ts", starter, harnessFile: "main.ts", harness }
    : { solutionFile: "solution.js", starter, harnessFile: "main.js", harness };
}

export const javascript = (iface: Interface) => generate(iface, false);
export const typescript = (iface: Interface) => generate(iface, true);
