"""Generate TypedDict row types from the migrated schema (ADR-0002 option C).

Usage: python -m interval_db.codegen <DATABASE_URL> <output-file>
"""

import json
import keyword
import sys
from dataclasses import dataclass
from pathlib import Path

import psycopg

# dbmate's bookkeeping table is not part of the application schema.
EXCLUDED_TABLES = frozenset({"schema_migrations"})

# Postgres type -> (annotation, name the annotation needs imported or defined).
# `vector` is deliberately absent: without a pgvector adapter psycopg returns it as
# text, so its mapping is decided when the embeddings slice adds the adapter.
SCALARS: dict[str, tuple[str, str | None]] = {
    "text": ("str", None),
    "varchar": ("str", None),
    "int2": ("int", None),
    "int4": ("int", None),
    "int8": ("int", None),
    "bool": ("bool", None),
    "float4": ("float", None),
    "float8": ("float", None),
    "numeric": ("Decimal", "Decimal"),
    "timestamptz": ("datetime", "datetime"),
    "timestamp": ("datetime", "datetime"),
    "date": ("date", "date"),
    "uuid": ("UUID", "UUID"),
    "json": ("JsonValue", "JsonValue"),
    "jsonb": ("JsonValue", "JsonValue"),
    "bytea": ("bytes", None),
}

IMPORTS: dict[str, str] = {
    "date": "from datetime import date",
    "datetime": "from datetime import datetime",
    "Decimal": "from decimal import Decimal",
    "Literal": "from typing import Literal",
    "TypedDict": "from typing import TypedDict",
    "UUID": "from uuid import UUID",
}

DOCSTRING = '"""Generated by interval_db.codegen. Do not edit."""'

JSON_ALIASES = (
    "type JsonScalar = str | int | float | bool | None\n"
    "type JsonValue = JsonScalar | list[JsonValue] | dict[str, JsonValue]"
)

RESERVED_CLASS_NAMES = frozenset({"JsonScalar", "JsonValue", *IMPORTS})

# Marks an enum in the set of names an annotation needs.
ENUM_PREFIX = "enum:"


class UnknownTypeError(Exception):
    pass


class InvalidNameError(Exception):
    pass


@dataclass(frozen=True)
class Column:
    table: str
    name: str
    position: int
    data_type: str
    udt_name: str
    nullable: bool


def _resolve(column: Column, enums: dict[str, list[str]]) -> tuple[str, set[str]]:
    if column.data_type == "ARRAY":
        element = Column(
            table=column.table,
            name=column.name,
            position=column.position,
            data_type="",
            udt_name=column.udt_name.removeprefix("_"),
            nullable=False,
        )
        inner, names = _resolve(element, enums)
        base = f"list[{inner}]"
    elif column.udt_name in enums:
        # Enums become named aliases (`type X = Literal[...]`), like kysely-codegen.
        base, names = class_name(column.udt_name), {ENUM_PREFIX + column.udt_name}
    elif column.udt_name in SCALARS:
        base, needed = SCALARS[column.udt_name]
        names: set[str] = {needed} if needed else set()
    else:
        raise UnknownTypeError(
            f"{column.table}.{column.name}: "
            f"no Python mapping for Postgres type {column.udt_name}"
        )
    return (f"{base} | None" if column.nullable else base), names


def python_type(column: Column, *, enums: dict[str, list[str]]) -> str:
    return _resolve(column, enums)[0]


def class_name(table: str) -> str:
    return "".join(part.capitalize() for part in table.split("_"))


def _check_identifier(name: str, where: str) -> None:
    if not name.isidentifier() or keyword.iskeyword(name):
        raise InvalidNameError(f"{where}: {name!r} is not a usable Python identifier")


def render(columns: list[Column], *, enums: dict[str, list[str]]) -> str:
    by_table: dict[str, list[Column]] = {}
    for column in columns:
        by_table.setdefault(column.table, []).append(column)

    classes: list[str] = []
    used: set[str] = set()
    seen_classes: dict[str, str] = {}

    def claim(name: str, owner: str) -> None:
        _check_identifier(name, owner)
        if name in RESERVED_CLASS_NAMES or name in seen_classes:
            other = seen_classes.get(name, "a generated name")
            raise InvalidNameError(f"{owner}: name {name} collides with {other}")
        seen_classes[name] = owner

    for table in sorted(by_table):
        name = class_name(table)
        claim(name, f"table {table}")
        used.add("TypedDict")

        lines = [f"class {name}(TypedDict):"]
        for c in sorted(by_table[table], key=lambda c: c.position):
            _check_identifier(c.name, f"column {table}.{c.name}")
            annotation, names = _resolve(c, enums)
            used |= names
            lines.append(f"    {c.name}: {annotation}")
        classes.append("\n".join(lines) + "\n")

    aliases: list[str] = []
    for enum in sorted(
        n.removeprefix(ENUM_PREFIX) for n in used if n.startswith(ENUM_PREFIX)
    ):
        name = class_name(enum)
        claim(name, f"enum {enum}")
        labels = ", ".join(json.dumps(label) for label in enums[enum])
        aliases.append(f"type {name} = Literal[{labels}]")
        used.add("Literal")

    blocks = [DOCSTRING]
    imports = sorted(line for name, line in IMPORTS.items() if name in used)
    if imports:
        blocks.append("\n".join(imports))
    if "JsonValue" in used:
        blocks.append(JSON_ALIASES)
    if aliases:
        blocks.append("\n".join(aliases))
    head = "\n\n".join(blocks) + "\n"
    return head + "\n\n" + "\n\n".join(classes) if classes else head


def read_schema(url: str) -> tuple[list[Column], dict[str, list[str]]]:
    with psycopg.connect(url) as conn, conn.cursor() as cur:
        # Tables and views in `public`, matching kysely-codegen's --include-pattern.
        cur.execute(
            """
            select c.table_name, c.column_name, c.ordinal_position,
                   c.data_type, c.udt_name, c.is_nullable = 'YES'
            from information_schema.columns c
            join information_schema.tables t
              on t.table_schema = c.table_schema and t.table_name = c.table_name
            where c.table_schema = 'public'
              and t.table_type in ('BASE TABLE', 'VIEW')
            """
        )
        columns = [
            Column(
                table=row[0],
                name=row[1],
                position=row[2],
                data_type=row[3],
                udt_name=row[4],
                nullable=row[5],
            )
            for row in cur.fetchall()
            if row[0] not in EXCLUDED_TABLES
        ]
        cur.execute(
            """
            select t.typname, e.enumlabel
            from pg_enum e
            join pg_type t on t.oid = e.enumtypid
            join pg_namespace n on n.oid = t.typnamespace
            where n.nspname = 'public'
            order by t.typname, e.enumsortorder
            """
        )
        enums: dict[str, list[str]] = {}
        for typname, label in cur.fetchall():
            enums.setdefault(typname, []).append(label)
    return columns, enums


def main(argv: list[str]) -> None:
    if len(argv) != 3:
        raise SystemExit(
            "usage: python -m interval_db.codegen <DATABASE_URL> <output-file>"
        )
    columns, enums = read_schema(argv[1])
    Path(argv[2]).write_text(render(columns, enums=enums), encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv)
